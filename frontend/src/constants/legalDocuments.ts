/** Every word of the full text in reading order (tests compare it with the reviewed source). */
export function legalDocumentText(document: LegalDocument): string[] {
  const lines: string[] = [document.title];
  if (document.intro) lines.push(document.intro);
  for (const section of document.sections) {
    lines.push(section.heading);
    for (const block of section.blocks) {
      if (block.kind === 'paragraph') lines.push(block.text);
      else if (block.kind === 'list') lines.push(...block.items);
      else if (block.kind === 'table') {
        // As drawn: one card per row, each cell under its column's name.
        for (const row of block.rows) row.forEach((cell, index) => lines.push(block.columns[index], cell));
      } else lines.push(block.label);
    }
  }
  return lines;
}
