/**
 * 이용약관 and 개인정보처리방침 shown inside the app (2026-11-13): the signup
 * screen's 자세히 보기 opens one of them. Each document is the reviewed text
 * word for word (tables included), plus a short summary of its key points
 * that adds nothing the text does not say.
 *
 * `version` is what signup sends for the document (frontend/src/constants/
 * legal.ts → backend CURRENT_TERMS_VERSION / CURRENT_PRIVACY_VERSION). It is
 * the revision label of the published page, never shown as an effective date.
 * Changing a document's text means raising its version on both sides
 * (legalDocuments.test.ts pins each text to its version).
 */
import { PRIVACY_VERSION, TERMS_VERSION } from './legal.ts';

export type LegalBlock =
  | { kind: 'paragraph'; text: string }
  | { kind: 'list'; ordered: boolean; items: readonly string[] }
  /** Rendered as one card per row (every cell under its column name) so no cell is cut on a phone. */
  | { kind: 'table'; columns: readonly string[]; rows: readonly (readonly string[])[] }
  | { kind: 'link'; label: string; url: string };

export type LegalSection = { heading: string; blocks: readonly LegalBlock[] };

export type LegalDocumentKind = 'terms' | 'privacy';

export type LegalDocument = {
  kind: LegalDocumentKind;
  title: string;
  version: string;
  /** 핵심 내용 요약: shown first, before the full text. */
  summary: readonly string[];
  /** Text before the first section, if any. */
  intro?: string;
  sections: readonly LegalSection[];
};

